class StudyPost {
  final String id;
  final String title;
  final String examType;
  final String region;
  final String targetScore;
  final int members;
  final int capacity;

  const StudyPost({
    required this.id,
    required this.title,
    required this.examType,
    required this.region,
    required this.targetScore,
    required this.members,
    required this.capacity,
  });
}
